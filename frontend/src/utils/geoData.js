export const getDistrictsForDivision = (division) => {
  return DISTRICTS_BY_DIVISION[division] || RAJSHAHI_DISTRICTS;
};

export const getUpazilasForDistrict = (district) => {
  return UPAZILAS_BY_DISTRICT[district] || ['শিবগঞ্জ', 'সদর', 'শেরপুর', 'গাবতলী'];
};

export const getMouzasForUpazila = (upazila) => {
  if (upazila === 'শিবগঞ্জ') return SHIBGANJ_MOUZAS;
  return SHIBGANJ_MOUZAS.slice(0, 10);
};

export const getJlNoForMouza = (mouzaName) => {
  const match = SHIBGANJ_MOUZAS.find(m => m.mouza === mouzaName);
  return match ? match.jl_no : '1';
};
